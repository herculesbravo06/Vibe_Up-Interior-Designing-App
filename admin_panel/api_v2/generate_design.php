<?php
// api_v2/generate_design.php
header("Access-Control-Allow-Origin: *");
header("Content-Type: application/json; charset=UTF-8");
header("Access-Control-Allow-Methods: POST");
header("Access-Control-Max-Age: 3600");
header("Access-Control-Allow-Headers: Content-Type, Access-Control-Allow-Headers, Authorization, X-Requested-With");

require_once '../config/database.php';

$db = new Database();
$conn = $db->getConnection();

$data = json_decode(file_get_contents("php://input"));

if(empty($data->user_id) || empty($data->original_prompt) || empty($data->selected_style)) {
    echo json_encode(["status" => "error", "message" => "Missing required fields (user_id, original_prompt, selected_style)."]);
    exit;
}

$user_id = $data->user_id;
$original_prompt = $data->original_prompt;
$selected_style = $data->selected_style;
$enhanced_prompt = $data->enhanced_prompt ?? "Enhanced: " . $original_prompt; // Typically generated by Gemini

// Generate an ID for the Request
$request_id = uniqid('REQ_');

$stmt = $conn->prepare("INSERT INTO design_requests (id, user_id, original_prompt, enhanced_prompt, selected_style) VALUES (:id, :uid, :oprompt, :eprompt, :style)");
$stmt->bindParam(':id', $request_id);
$stmt->bindParam(':uid', $user_id);
$stmt->bindParam(':oprompt', $original_prompt);
$stmt->bindParam(':eprompt', $enhanced_prompt);
$stmt->bindParam(':style', $selected_style);

if ($stmt->execute()) {
    
    // Also create a moodboard stub for this request
    $moodboard_id = uniqid('MB_');
    $mb_stmt = $conn->prepare("INSERT INTO moodboards (id, request_id, style) VALUES (:mid, :reqid, :style)");
    $mb_stmt->bindParam(':mid', $moodboard_id);
    $mb_stmt->bindParam(':reqid', $request_id);
    $mb_stmt->bindParam(':style', $selected_style);
    $mb_stmt->execute();

    echo json_encode([
        "status" => "success",
        "message" => "Design request saved.",
        "request_id" => $request_id,
        "moodboard_id" => $moodboard_id
    ]);
} else {
    echo json_encode(["status" => "error", "message" => "Failed to save design request."]);
}
?>
